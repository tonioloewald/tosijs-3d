/*
Writes src/ual-rest.ts: UAL's rest pose (each joint's parent, local
translation and rotation) read from UAL1.glb's armature (Quaternius,
Universal Animation Library, CC0 1.0), in the order of the 65-joint export
profile. The rigged-body writer gives every joint these frames, so UAL's
clips play on its files by name.

  bun bin/ual-rest.ts [path to a UAL GLB]

Default source: ../static-assets/assets/quaternius/UAL1.glb.
*/
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { readGlb } from '../src/glb-chunks.js'

const source =
  process.argv[2] ??
  join(
    import.meta.dir,
    '..',
    '..',
    'static-assets',
    'assets',
    'quaternius',
    'UAL1.glb'
  )

// The profile's order: the spine and head, the left arm and fingers, the left
// leg, then the right (Dramatis's export-format, "Skeleton").
const side = (s: string): Array<[string, string]> => [
  [`clavicle_${s}`, 'spine_03'],
  [`upperarm_${s}`, `clavicle_${s}`],
  [`lowerarm_${s}`, `upperarm_${s}`],
  [`hand_${s}`, `lowerarm_${s}`],
  ...['thumb', 'index', 'middle', 'ring', 'pinky'].flatMap(
    (f): Array<[string, string]> => [
      [`${f}_01_${s}`, `hand_${s}`],
      [`${f}_02_${s}`, `${f}_01_${s}`],
      [`${f}_03_${s}`, `${f}_02_${s}`],
      [`${f}_04_leaf_${s}`, `${f}_03_${s}`],
    ]
  ),
  [`thigh_${s}`, 'pelvis'],
  [`calf_${s}`, `thigh_${s}`],
  [`foot_${s}`, `calf_${s}`],
  [`ball_${s}`, `foot_${s}`],
  [`ball_leaf_${s}`, `ball_${s}`],
]
const PROFILE: Array<[string, string | null]> = [
  ['root', null],
  ['pelvis', 'root'],
  ['spine_01', 'pelvis'],
  ['spine_02', 'spine_01'],
  ['spine_03', 'spine_02'],
  ['neck_01', 'spine_03'],
  ['Head', 'neck_01'],
  ...side('l'),
  ...side('r'),
]

const glb = readGlb(new Uint8Array(readFileSync(source)))
type Node = {
  name?: string
  translation?: number[]
  rotation?: number[]
  children?: number[]
}
const nodes = glb.json.nodes as Node[]
const parentOf = new Map<number, number>()
nodes.forEach((n, i) => n.children?.forEach((c) => parentOf.set(c, i)))
const index = new Map(nodes.flatMap((n, i) => (n.name ? [[n.name, i]] : [])))
const round = (v: number): number => Number(v.toPrecision(9))
const rows = PROFILE.map(([name, parent]) => {
  const i = index.get(name)
  if (i == null) throw new Error(`${source} has no joint ${name}`)
  const p = parentOf.get(i)
  if ((p == null ? null : nodes[p].name) !== parent && parent !== null)
    throw new Error(
      `${name}'s parent is ${p == null ? 'none' : nodes[p].name}, not ${parent}`
    )
  const n = nodes[i]
  const t = (n.translation ?? [0, 0, 0]).map(round)
  const r = (n.rotation ?? [0, 0, 0, 1]).map(round)
  return `  [${JSON.stringify(name)}, ${JSON.stringify(parent)}, [${t.join(
    ', '
  )}], [${r.join(', ')}]],`
})
writeFileSync(
  join(import.meta.dir, '..', 'src', 'ual-rest.ts'),
  `/*
GENERATED by bin/ual-rest.ts from UAL1.glb's armature (Quaternius, Universal
Animation Library, CC0 1.0, https://quaternius.com). Do not edit.

UAL's rest pose in the order of the 65-joint export profile: each joint's
name, parent, local translation (metres) and rotation (x, y, z, w). Pure
data, in the character core.
*/

export const UAL_REST: ReadonlyArray<
  readonly [
    name: string,
    parent: string | null,
    translation: readonly [number, number, number],
    rotation: readonly [number, number, number, number]
  ]
> = [
${rows.join('\n')}
]
`
)
console.log(`src/ual-rest.ts: ${rows.length} joints from ${source}`)
