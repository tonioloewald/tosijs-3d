/*
Embed artwork as strings, so the library draws it without a fetch: the dials
(static/compass.svg, static/vr-watch.svg → src/dial-art.ts) and the glass
gamepad's clusters (static/gamepad-*.svg → src/gamepad-art.ts). An adopter's
site does not serve our static/ folder, so a fetched default 404s there (the
gamepad's did, until 0.11.1). The SVG files are the source of truth: edit them
(Tonio draws them in AMDN), then run `bun run dial-art`. The parts the code
drives are found by id, so keep those names when redrawing (see src/dials.ts
and src/glass-gamepad.ts).
*/
async function embed(
  target: string,
  art: Record<string, string>
): Promise<void> {
  let out =
    '// GENERATED by bin/dial-art.ts from ' +
    Object.values(art).join(', ') +
    '. Do not edit: edit the SVGs and run `bun run dial-art`.\n\n'
  for (const [name, path] of Object.entries(art)) {
    const svg = (await Bun.file(path).text())
      .replace(/<\?xml[^>]*\?>\s*/, '')
      .replace(/<!--[\s\S]*?-->\s*/g, '')
      .trim()
    // In the shape prettier would give it, so `bun format` leaves it alone.
    const quoted =
      "'" +
      svg.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, '\\n') +
      "'"
    out += `export const ${name}Svg =\n  ${quoted}\n`
  }
  await Bun.write(target, out)
  console.log('wrote ' + target)
}

await embed('src/dial-art.ts', {
  compass: 'static/compass.svg',
  watch: 'static/vr-watch.svg',
})
await embed('src/gamepad-art.ts', {
  gamepadLeft: 'static/gamepad-left.svg',
  gamepadRight: 'static/gamepad-right.svg',
  gamepadTop: 'static/gamepad-top.svg',
})
