/**
 * THE HARNESS for the interesting/boring split (GALAXY-DESIGN.md →
 * "Interesting stars"). Scores a corpus of candidate stars per spectral cell
 * with the REAL planet generation and HI, and writes the pass rates to
 * `src/population-table.ts`.
 *
 *   bun bin/tune-populations.ts            # N = 5000 per cell (~3 s)
 *   bun bin/tune-populations.ts --n 20000  # tighter rates
 *
 * Rerun it whenever star-system generation or HI changes; the galaxy reads the
 * table, so nothing else is rebuilt. `star-populations.test.ts` fails until you
 * do (it fingerprints HI).
 */
import path from 'path'
import { writeFileSync } from 'fs'
import {
  SPECTRAL_CELLS,
  bestHIOf,
  corpusStar,
  hiFingerprint,
  INTERESTING_MAX_HI,
} from '../src/star-populations.js'

const at = process.argv.indexOf('--n')
const N = at >= 0 ? Number(process.argv[at + 1]) : 5000
const t0 = performance.now()

const rates: Record<string, number> = {}
SPECTRAL_CELLS.forEach((cell, c) => {
  let pass = 0
  for (let i = 0; i < N; i++) {
    // Corpus seeds: disjoint from the fingerprint's probe seeds.
    const seed = (Math.imul(c * 1_000_003 + i + 1, 0x85ebca6b) ^ 0xc0ffee) >>> 0
    if (
      bestHIOf(corpusStar(cell[0], Number(cell[1]), seed)) <= INTERESTING_MAX_HI
    )
      pass++
  }
  rates[cell] = Number((pass / N).toFixed(4))
})
const fingerprint = hiFingerprint()
const ms = performance.now() - t0

const rows = SPECTRAL_CELLS.map((c) => `  ${c}: ${rates[c]},`).join('\n')
const out = `/*
GENERATED by bin/tune-populations.ts — do not edit. Rerun it after changing
star-system generation or HI (star-populations.test.ts fails until you do).

${N} corpus stars per spectral cell, scored with the real rules. A cell's
rate is the fraction whose best planet has HI <= ${INTERESTING_MAX_HI}.
*/

/** What counts as interesting: a planet with HI at or below this. */
export const INTERESTING_MAX_HI = ${INTERESTING_MAX_HI}

/** Corpus size per cell. */
export const CORPUS_PER_CELL = ${N}

/** The HI rules these rates were measured against — see hiFingerprint. */
export const HI_FINGERPRINT = '${fingerprint}'

/** Fraction of each cell's systems that are interesting. */
export const PASS_RATE: Readonly<Record<string, number>> = {
${rows}
}
`
const file = path.resolve(import.meta.dir, '../src/population-table.ts')
writeFileSync(file, out)
console.log(
  `scored ${SPECTRAL_CELLS.length} cells × ${N} in ${(ms / 1000).toFixed(
    1
  )} s · fingerprint ${fingerprint}`
)
for (const cls of ['G', 'K', 'M'])
  console.log(
    cls,
    Array.from({ length: 10 }, (_, i) => rates[`${cls}${i}`].toFixed(3)).join(
      ' '
    )
  )
console.log(`wrote ${path.relative(process.cwd(), file)}`)
